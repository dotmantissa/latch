"""Provisional raster observations. Agreement conveys no requester authority."""

from typing import Annotated, Literal
from uuid import UUID

from pydantic import Field, StrictInt, model_validator

from services.common.source_policy import StrictRecord
from services.domain.contracts import content_hash
from services.domain.extraction import Quote

VERSION = "raster-correspondence-v1"
Hash = Annotated[str, Field(pattern=r"^[a-f0-9]{64}$")]


class Observation(StrictRecord):
    page_index: Annotated[StrictInt, Field(ge=0, le=1)]
    item_key: str | None
    status: Literal["agrees", "disagrees", "abstains"]
    reason: Literal["visible_match", "visible_conflict", "not_visible", "uncertain"]
    evidence: list[Quote] = Field(max_length=2)
    # Pixel coordinates in the supplied immutable raster; no crop generated by a model.
    region: list[Annotated[StrictInt, Field(ge=0, le=16000)]] | None = Field(
        default=None,
        min_length=4,
        max_length=4,
    )

    @model_validator(mode="after")
    def supported(self):
        if self.status != "abstains" and (
            not self.evidence
            or self.region is None
            or self.reason
            != {"agrees": "visible_match", "disagrees": "visible_conflict"}[self.status]
        ):
            raise ValueError("Visible conclusions require attributed evidence and a region")
        if self.status == "abstains" and self.reason not in ("not_visible", "uncertain"):
            raise ValueError("Abstention requires an uncertainty reason")
        return self


class ProposedCorrespondence(StrictRecord):
    observations: list[Observation] = Field(min_length=1, max_length=5)


class Correspondence(StrictRecord):
    source_id: UUID
    capture_hash: Hash
    raster_hashes: list[Hash] = Field(min_length=1, max_length=2)
    model_id: str = Field(min_length=1, max_length=100)
    version: Literal["raster-correspondence-v1"] = VERSION
    observations: list[Observation] = Field(min_length=1, max_length=5)
    result_hash: Hash


def validate(result: Correspondence, pages: list[dict], item_keys: set[str]):
    expected = {(i, None) for i in range(len(pages))} | {(0, key) for key in item_keys}
    actual = [(o.page_index, o.item_key) for o in result.observations]
    if len(actual) != len(expected) or set(actual) != expected:
        raise ValueError("Complete distinct page and item correspondence required")
    if result.raster_hashes != [p["sanitized_hash"] for p in pages]:
        raise ValueError("Correspondence belongs to another raster")
    for o in result.observations:
        page = pages[o.page_index]
        for q in o.evidence:
            if q.page_index != o.page_index or page["text"].count(q.quote) != 1:
                raise ValueError("Correspondence requires exact unique captured text")
        if o.region is not None:
            x, y, width, height = o.region
            if width < 1 or height < 1 or x + width > page["width"] or y + height > page["height"]:
                raise ValueError("Correspondence region outside captured raster")
    if content_hash(result.model_dump(mode="json", exclude={"result_hash"})) != result.result_hash:
        raise ValueError("Correspondence hash mismatch")


def ground(proposal, *, source_id, capture_hash, pages, item_keys, model_id):
    body = {
        "source_id": str(source_id),
        "capture_hash": capture_hash,
        "raster_hashes": [p["sanitized_hash"] for p in pages],
        "model_id": model_id,
        "version": VERSION,
        "observations": proposal.model_dump(mode="json")["observations"],
    }
    result = Correspondence(**body, result_hash=content_hash(body))
    validate(result, pages, item_keys)
    return result


def blockers(result: Correspondence | None) -> list[str]:
    if result is None:
        return ["IMAGE_CORRESPONDENCE_MISSING"]
    return sorted(
        {
            "IMAGE_TEXT_DISAGREEMENT"
            if o.status == "disagrees"
            else "IMAGE_CORRESPONDENCE_UNRESOLVED"
            for o in result.observations
            if o.status != "agrees"
        }
    )
